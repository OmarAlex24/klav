//! Task requests (ADR 0021, `docs/api.md` §8): the agent asks for a set of
//! items and permissions at once, the person approves one card and the
//! server lets the agent use that set until the task expires.
//!
//! The request ([`klav_core::task::TaskRequest`]) and the decision
//! ([`klav_core::task::TaskDecision`]) travel as the exact JSON bytes that
//! were signed (spec §13.8): the agent's request body is stored verbatim,
//! and the person signs it together with the decision.

use klav_core::ids::{AgentId, TaskId};
use serde::{Deserialize, Serialize};

use crate::Blob;

/// Longest `?wait=` of `GET /v1/agent/tasks/{id}` (seconds, like
/// approvals: ADR 0015 §4).
pub const MAX_TASK_WAIT_SECS: u64 = 30;
/// How long a person has to answer a task request (Unix ms), like an
/// approval request.
pub const TASK_DECIDE_TTL_MS: i64 = 10 * 60 * 1000;
/// Pending task requests per agent (ADR 0021 §7).
pub const MAX_PENDING_TASKS: i64 = 5;
/// Live (approved, not ended) tasks per agent (ADR 0021 §7).
pub const MAX_LIVE_TASKS: i64 = 10;

/// State of a task.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum TaskStatus {
    /// Waiting for the person.
    Pending,
    /// Approved and running until `expires_at`.
    Approved,
    /// The person denied it.
    Denied,
    /// Nobody decided in time.
    Expired,
    /// It ran and ended: see [`TaskInfo::ended_by`].
    Ended,
}

impl TaskStatus {
    /// Storage form.
    pub const fn as_str(self) -> &'static str {
        match self {
            TaskStatus::Pending => "pending",
            TaskStatus::Approved => "approved",
            TaskStatus::Denied => "denied",
            TaskStatus::Expired => "expired",
            TaskStatus::Ended => "ended",
        }
    }

    /// Parses [`TaskStatus::as_str`].
    pub fn parse(text: &str) -> Option<Self> {
        Some(match text {
            "pending" => TaskStatus::Pending,
            "approved" => TaskStatus::Approved,
            "denied" => TaskStatus::Denied,
            "expired" => TaskStatus::Expired,
            "ended" => TaskStatus::Ended,
            _ => return None,
        })
    }
}

/// Who or what ended an approved task (ADR 0021 §9).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum TaskEndedBy {
    /// The person («End task»), with a signature.
    Person,
    /// The agent, when it finished (`end_task`).
    Agent,
    /// It reached `expires_at`.
    Expiry,
    /// The agent was revoked.
    Revocation,
}

impl TaskEndedBy {
    /// Storage form.
    pub const fn as_str(self) -> &'static str {
        match self {
            TaskEndedBy::Person => "person",
            TaskEndedBy::Agent => "agent",
            TaskEndedBy::Expiry => "expiry",
            TaskEndedBy::Revocation => "revocation",
        }
    }

    /// Parses [`TaskEndedBy::as_str`].
    pub fn parse(text: &str) -> Option<Self> {
        Some(match text {
            "person" => TaskEndedBy::Person,
            "agent" => TaskEndedBy::Agent,
            "expiry" => TaskEndedBy::Expiry,
            "revocation" => TaskEndedBy::Revocation,
            _ => return None,
        })
    }
}

/// A task as stored.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TaskInfo {
    /// ID (generated by the server).
    pub id: TaskId,
    /// The agent.
    pub agent_id: AgentId,
    /// Its name.
    pub agent_name: String,
    /// State.
    pub status: TaskStatus,
    /// The agent's request: JSON bytes of `klav_core::task::TaskRequest`,
    /// exactly as signed. Empty for a task the person offered (ADR 0022
    /// §6), whose decision carries the title and reason.
    pub request: Blob,
    /// Asked at (Unix ms).
    pub created_at: i64,
    /// Decide before (Unix ms).
    pub decide_by: i64,
    /// Decided at (Unix ms), as signed.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub decided_at: Option<i64>,
    /// The decision in force: JSON bytes of `klav_core::task::TaskDecision`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub decision: Option<Blob>,
    /// The account's signature on it (spec §13.8).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub signature: Option<Blob>,
    /// Revision of the decision in force (0 while pending).
    #[serde(default)]
    pub revision: u64,
    /// When an approved task ends (Unix ms).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub expires_at: Option<i64>,
    /// When it ended (Unix ms).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub ended_at: Option<i64>,
    /// Who ended it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub ended_by: Option<TaskEndedBy>,
}

/// `GET /v1/tasks` and `GET /v1/agent/tasks`.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TaskList {
    /// Newest first.
    pub tasks: Vec<TaskInfo>,
}

/// `POST /v1/agent/tasks` → `202`.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PendingTask {
    /// Ask the person to decide, then follow it with
    /// `GET /v1/agent/tasks/{id}?wait=N`.
    pub pending_task_id: TaskId,
    /// Until when the person can decide (Unix ms).
    pub expires_at: i64,
}

/// `POST /v1/tasks/{id}/decide`: the first decision, a denial, or a
/// revision («Add to the task», ADR 0021 §6).
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct DecideTask {
    /// Approve or deny.
    pub approve: bool,
    /// JSON bytes of `klav_core::task::TaskDecision`, as signed.
    pub decision: Blob,
    /// When the person decided (Unix ms), as signed.
    pub decided_at: i64,
    /// Signature by the account identity (spec §13.8).
    pub signature: Blob,
}

/// `POST /v1/tasks`: the person offers an agent a task without a request
/// (ADR 0022 §6). The person's client picks the task ID, since it is part
/// of what the account signs; the stored request is empty.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct OfferTask {
    /// New task ID (409 if taken).
    pub task_id: TaskId,
    /// The agent it is offered to.
    pub agent_id: AgentId,
    /// JSON bytes of `klav_core::task::TaskDecision`, with `offer`, as
    /// signed.
    pub decision: Blob,
    /// When the person decided (Unix ms), as signed.
    pub decided_at: i64,
    /// Signature by the account identity over an empty request (spec
    /// §13.8).
    pub signature: Blob,
}

/// `POST /v1/tasks/{id}/end`: the person ends a task.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct EndTask {
    /// When (Unix ms), as signed.
    pub ended_at: i64,
    /// Signature by the account identity (spec §13.8, `task-end`).
    pub signature: Blob,
}

/// `POST /v1/agent/tasks/{id}/end`: the agent ends its task.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AgentEndTask {
    /// Why (mandatory, like every agent reason).
    pub reason: String,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn statuses_roundtrip() {
        for status in [
            TaskStatus::Pending,
            TaskStatus::Approved,
            TaskStatus::Denied,
            TaskStatus::Expired,
            TaskStatus::Ended,
        ] {
            assert_eq!(TaskStatus::parse(status.as_str()), Some(status));
            assert_eq!(
                serde_json::to_value(status).unwrap(),
                serde_json::Value::String(status.as_str().into())
            );
        }
        for by in [
            TaskEndedBy::Person,
            TaskEndedBy::Agent,
            TaskEndedBy::Expiry,
            TaskEndedBy::Revocation,
        ] {
            assert_eq!(TaskEndedBy::parse(by.as_str()), Some(by));
            assert_eq!(
                serde_json::to_value(by).unwrap(),
                serde_json::Value::String(by.as_str().into())
            );
        }
        assert_eq!(TaskStatus::parse("nope"), None);
    }
}
