/// An agent that may start sandboxes through the credential proxy, as the
/// account signed it into the proxy's grant (ADR 0036 §4). The proxy checks
/// the issuer's requests with this identity, never one from the server.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SandboxIssuer {
    /// The issuer.
    pub agent_id: AgentId,
    /// Its public identity (66 bytes, kind `0x05`), the one the person
    /// approved.
    pub public_identity: Blob,
    /// Names of this grant's profiles its sandboxes may use.
    pub profiles: Vec<String>,
    /// Longest TTL it may give a sandbox, in seconds.
    pub max_ttl_secs: u64,
    /// Most of its sandboxes alive at once.
    pub max_live: u32,
}

/// A profile's name: 1 to [`MAX_PROFILE_NAME`] lower-case letters, digits
/// or `-`, starting with a letter (so never `_klav`).
pub fn profile_name_ok(name: &str) -> bool {
    (1..=MAX_PROFILE_NAME).contains(&name.len())
        && name.starts_with(|c: char| c.is_ascii_lowercase())
        && name
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
}

impl SandboxIssuer {
    /// The TTL of a sandbox that asked for `wanted` seconds (or nothing):
    /// the default, never past this issuer's limit.
    pub fn ttl_secs(&self, wanted: Option<u64>) -> Result<u64, String> {
        match wanted {
            None => Ok(DEFAULT_SANDBOX_TTL_SECS.min(self.max_ttl_secs)),
            Some(0) => Err("a sandbox needs a TTL of at least one second".into()),
            Some(t) if t > self.max_ttl_secs => Err(format!(
                "a TTL of {t} s is longer than this issuer may give ({} s)",
                self.max_ttl_secs
            )),
            Some(t) => Ok(t),
        }
    }
}

