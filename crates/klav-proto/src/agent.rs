pub const HEADER_TIMESTAMP: &str = "klav-timestamp";
/// Header with the request nonce (16 bytes, base64url without padding).
pub const HEADER_NONCE: &str = "klav-nonce";
/// Header with the Ed25519 signature (64 bytes, base64url without padding).
pub const HEADER_SIGNATURE: &str = "klav-signature";

/// Longest agent name.
pub const MAX_AGENT_NAME: usize = 64;

/// State of an agent.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum AgentStatus {
    /// Registered, waiting for the person to approve it.
    Pending,
    /// Approved: it has a grant and its signed requests are served.
    Active,
    /// The person rejected the registration (or it lapsed).
    Denied,
    /// Revoked: every request is refused.
    Revoked,
}

impl AgentStatus {
    /// Text form used in the database.
    pub const fn as_str(self) -> &'static str {
        match self {
            AgentStatus::Pending => "pending",
            AgentStatus::Active => "active",
            AgentStatus::Denied => "denied",
            AgentStatus::Revoked => "revoked",
        }
    }

    /// Parses [`AgentStatus::as_str`].
    pub fn parse(text: &str) -> Option<Self> {
        Some(match text {
            "pending" => AgentStatus::Pending,
            "active" => AgentStatus::Active,
            "denied" => AgentStatus::Denied,
            "revoked" => AgentStatus::Revoked,
            _ => return None,
        })
    }
}

