/// Longest profile name.
pub const MAX_PROFILE_NAME: usize = 32;
/// Longest header name of a profile.
pub const MAX_PROFILE_HEADER: usize = 64;
/// Longest text before the value in the header.
pub const MAX_PROFILE_PREFIX: usize = 64;
/// Longest field name of a profile.
pub const MAX_PROFILE_FIELD: usize = 64;
/// Longest MCP endpoint path (ADR 0049 §2.1).
pub const MAX_MCP_ENDPOINT: usize = 64;
/// Most fixed headers an MCP profile may carry.
pub const MAX_MCP_HEADERS: usize = 4;
/// Longest value of an MCP profile's fixed header.
pub const MAX_MCP_HEADER_VALUE: usize = 128;
/// Calls per minute of a profile without `rate_per_minute` (ADR 0036 §8).
pub const DEFAULT_PROFILE_RATE: u32 = 60;
/// Most calls per minute a profile may allow.
pub const MAX_PROFILE_RATE: u32 = 6000;

/// Headers a profile may not set: framing, hop-by-hop, the proxy's own and
/// Klav's. The proxy sets or strips them itself.
const RESERVED_HEADERS: [&str; 12] = [
    "host",
    "content-length",
    "transfer-encoding",
    "connection",
    "keep-alive",
    "te",
    "trailer",
    "upgrade",
    "expect",
    "forwarded",
    "proxy-authorization",
    "proxy-connection",
];

/// Headers an MCP profile's fixed headers may not set, beyond
/// [`RESERVED_HEADERS`]: credentials, and the ones the MCP transport and
/// the proxy handle themselves (ADR 0049 §2.1, §2.4, §5.1).
const RESERVED_MCP_HEADERS: [&str; 11] = [
    "authorization",
    "cookie",
    "www-authenticate",
    "mcp-session-id",
    "mcp-protocol-version",
    "last-event-id",
    "content-type",
    "content-encoding",
    "accept",
    "accept-encoding",
    "origin",
];

/// Whether `name` is a lower-case header name a profile may set: 1–64 of
/// `a-z 0-9 -`, none of [`RESERVED_HEADERS`], not `klav-…` or `proxy-…`.
fn settable_header(name: &str) -> bool {
    (1..=MAX_PROFILE_HEADER).contains(&name.len())
        && name
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
        && !RESERVED_HEADERS.contains(&name)
        && !name.starts_with("klav-")
        && !name.starts_with("proxy-")
}

/// What makes a profile an MCP profile (ADR 0049 §2.1): the upstream's MCP
/// endpoint, which the proxy reads, checks and filters, and the fixed
/// headers the person signed.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct McpProfile {
    /// The endpoint's path on `upstream`, canonical
    /// ([`klav_core::policy::is_canonical_path`]), at most 64 bytes. The
    /// profile forwards only this exact path.
    pub endpoint: String,
    /// At most 4 fixed, non-secret headers sent on every request.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub headers: Vec<McpHeader>,
}

/// One fixed header of an MCP profile.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct McpHeader {
    /// Lower-case name.
    pub name: String,
    /// Printable ASCII, at most 128 bytes.
    pub value: String,
}

/// A recipe signed by the account (ADR 0036 §2): which item's value goes
/// in which header, and where requests through it go. The hosts, methods
/// and paths it may reach are the `proxy` rules of the policy for its item;
/// `upstream` must be one of those hosts.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ProxyProfile {
    /// Name, such as `northflank`: lower-case letters, digits and `-`,
    /// starting with a letter. In mode (a) it is the first segment of the
    /// local URL.
    pub name: String,
    /// The item whose value it uses (one of the grant's `items`).
    pub item_id: ItemId,
    /// The field holding the value; absent: the item's main secret.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub field: Option<String>,
    /// The header the value goes in, in lower case (`authorization`,
    /// `project-access-token`).
    pub header: String,
    /// Text before the value, such as `Bearer `.
    #[serde(default, skip_serializing_if = "String::is_empty")]
    pub prefix: String,
    /// Where mode (a) sends requests: `https://host` or `https://host:port`,
    /// without path.
    pub upstream: String,
    /// Most calls per minute through this profile (default
    /// [`DEFAULT_PROFILE_RATE`]).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub rate_per_minute: Option<u32>,
    /// An MCP profile (`v: 4`, ADR 0049 §2.1): the proxy reads, checks and
    /// filters the JSON-RPC on `endpoint` and forwards nothing else.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub mcp: Option<McpProfile>,
}

impl ProxyProfile {
    /// The host and port of `upstream`, if it is well formed.
    pub fn upstream_host(&self) -> Option<(String, u16)> {
        parse_upstream(&self.upstream)
    }

    /// Calls per minute it allows.
    pub fn rate(&self) -> u32 {
        self.rate_per_minute.unwrap_or(DEFAULT_PROFILE_RATE)
    }

    fn check(&self) -> Result<(), String> {
        if !profile_name_ok(&self.name) {
            return Err(format!(
                "profile name {:?}: 1–32 lower-case letters, digits or -, starting with a letter",
                self.name
            ));
        }
        if !settable_header(&self.header) {
            return Err(format!(
                "profile {}: header {:?} is not a lower-case header name the proxy may set",
                self.name, self.header
            ));
        }
        if self.prefix.len() > MAX_PROFILE_PREFIX
            || !self.prefix.bytes().all(|b| (0x20..0x7f).contains(&b))
        {
            return Err(format!(
                "profile {}: the prefix must be visible ASCII, at most 64 characters",
                self.name
            ));
        }
        if let Some(field) = &self.field
            && (field.trim().is_empty()
                || field.chars().count() > MAX_PROFILE_FIELD
                || field.chars().any(klav_core::text::is_hidden))
        {
            return Err(format!("profile {}: invalid field name", self.name));
        }
        if self.upstream_host().is_none() {
            return Err(format!(
                "profile {}: upstream must be https://host[:port] without path, with a normalized host name (not an IP address)",
                self.name
            ));
        }
        if self
            .rate_per_minute
            .is_some_and(|r| r == 0 || r > MAX_PROFILE_RATE)
        {
            return Err(format!(
                "profile {}: rate_per_minute must be 1–{MAX_PROFILE_RATE}",
                self.name
            ));
        }
        if let Some(mcp) = &self.mcp {
            self.check_mcp(mcp)?;
        }
        Ok(())
    }

    fn check_mcp(&self, mcp: &McpProfile) -> Result<(), String> {
        if mcp.endpoint.len() > MAX_MCP_ENDPOINT
            || !klav_core::policy::is_canonical_path(&mcp.endpoint)
        {
            return Err(format!(
                "profile {}: the MCP endpoint must be a canonical path of at most {MAX_MCP_ENDPOINT} bytes",
                self.name
            ));
        }
        if mcp.headers.len() > MAX_MCP_HEADERS {
            return Err(format!(
                "profile {}: at most {MAX_MCP_HEADERS} fixed MCP headers",
                self.name
            ));
        }
        let mut seen = std::collections::HashSet::new();
        for h in &mcp.headers {
            let name_ok = settable_header(&h.name)
                && !RESERVED_MCP_HEADERS.contains(&h.name.as_str())
                && h.name != self.header;
            if !name_ok || !seen.insert(h.name.as_str()) {
                return Err(format!(
                    "profile {}: fixed MCP header {:?} is reserved, repeated or not a lower-case header name",
                    self.name, h.name
                ));
            }
            if h.value.len() > MAX_MCP_HEADER_VALUE
                || !h.value.bytes().all(|b| (0x20..0x7f).contains(&b))
            {
                return Err(format!(
                    "profile {}: the value of MCP header {} must be printable ASCII, at most {MAX_MCP_HEADER_VALUE} bytes",
                    self.name, h.name
                ));
            }
        }
        Ok(())
    }
}

/// `https://host[:port]` → `(host, port)`, with the host as the policy
/// matches it ([`klav_core::policy::normalize_host`], already normalized)
/// and a name, never an IP address ([`klav_core::policy::is_ip_literal`]).
fn parse_upstream(text: &str) -> Option<(String, u16)> {
    let rest = text.strip_prefix("https://")?;
    let (host, port) = match rest.rsplit_once(':') {
        Some((host, port)) => {
            let port: u16 = port.parse().ok().filter(|p| *p != 0)?;
            (host, port)
        }
        None => (rest, 443),
    };
    (klav_core::policy::normalize_host(host).as_deref() == Some(host)
        && !klav_core::policy::is_ip_literal(host))
    .then(|| (host.to_owned(), port))
}

impl GrantPayload {
    /// Checks what the signature cannot: that the payload is a format this
    /// build knows and keeps the rules of its version. Servers check it
    /// before storing a grant, the person's clients before showing one, and
    /// runtimes before using one; whatever fails is rejected (fail closed).
    ///
    /// * `v: 1` has no items, no profiles and nothing of [`Policy::needs_v2`].
    /// * `v: 2` may have them. A grant with items has no projects; its
    ///   items and profile names are unique; every profile uses an item of
    ///   the grant, **no two profiles use the same item**, and its upstream
    ///   host is allowed by a `proxy` rule for that item; every `proxy` rule
    ///   names only items of the grant; and the policy keeps
    ///   [`Policy::check_proxy`].
    ///
    /// Rules bind to items, not to profiles, so one profile per item keeps
    /// each profile's allowlist its own (ADR 0036 §8): two profiles on one
    /// token would otherwise share every host, method and path the rules
    /// allow for it. A later format may allow it; older runtimes then
    /// reject the duplicate, which fails closed.
    pub fn check_format(&self) -> Result<(), String> {
        if self.v < GRANT_PAYLOAD_VERSION_MCP && self.uses_mcp() {
            return Err(
                "a grant with MCP profiles, tool rules or local clients must be version 4".into(),
            );
        }
        match self.v {
            GRANT_PAYLOAD_VERSION => {
                if !self.items.is_empty() || !self.profiles.is_empty() || self.policy.needs_v2() {
                    return Err(
                        "a grant with items, profiles or proxy rules must be version 2".into(),
                    );
                }
                if !self.issuers.is_empty() || self.sandbox.is_some() {
                    return Err(
                        "a grant with sandbox issuers or a sandbox proxy must be version 3".into(),
                    );
                }
                return Ok(());
            }
            GRANT_PAYLOAD_VERSION_ITEMS => {
                if !self.issuers.is_empty() || self.sandbox.is_some() {
                    return Err(
                        "a grant with sandbox issuers or a sandbox proxy must be version 3".into(),
                    );
                }
            }
            GRANT_PAYLOAD_VERSION_SANDBOXES => {
                // One way to write each grant: version 3 only with what
                // needs it, so a v2 grant is never re-labelled 3.
                if self.issuers.is_empty() && self.sandbox.is_none() {
                    return Err(
                        "a version 3 grant carries sandbox issuers or a sandbox proxy".into(),
                    );
                }
                self.check_sandboxes()?;
            }
            GRANT_PAYLOAD_VERSION_MCP => {
                if !self.uses_mcp() {
                    return Err(
                        "a version 4 grant carries MCP profiles, tool rules or local clients"
                            .into(),
                    );
                }
                self.check_sandboxes()?;
            }
            v => return Err(format!("unsupported grant payload version {v}")),
        }
        self.policy.check_proxy().map_err(|e| e.to_string())?;
        if !self.items.is_empty() && !self.projects.is_empty() {
            return Err("a grant shares items or projects, not both".into());
        }
        let mut items = std::collections::HashSet::new();
        for item in &self.items {
            if !items.insert(item.item_id) {
                return Err(format!("item {} is granted twice", item.item_id));
            }
        }
        for rule in &self.policy.rules {
            if let Some(item) = rule.scope.items.iter().find(|i| !items.contains(*i)) {
                return Err(format!(
                    "a rule names item {item}, which the grant does not share"
                ));
            }
        }
        let mut names = std::collections::HashSet::new();
        let mut profiled = std::collections::HashSet::new();
        for profile in &self.profiles {
            profile.check()?;
            if !names.insert(profile.name.as_str()) {
                return Err(format!("profile {} appears twice", profile.name));
            }
            if !profiled.insert(profile.item_id) {
                return Err(format!(
                    "profile {}: item {} already has a profile (one profile per item)",
                    profile.name, profile.item_id
                ));
            }
            if !items.contains(&profile.item_id) {
                return Err(format!(
                    "profile {} uses an item the grant does not share",
                    profile.name
                ));
            }
            let (host, _) = profile.upstream_host().unwrap_or_default();
            let reachable = self.policy.rules.iter().any(|r| {
                r.permission == Permission::Proxy
                    && r.effect != klav_core::policy::Effect::Deny
                    && r.scope.items.contains(&profile.item_id)
                    && r.scope.domains.iter().any(|d| d.matches(&host))
            });
            if !reachable {
                return Err(format!(
                    "profile {}: no proxy rule lets its item reach {host}",
                    profile.name
                ));
            }
            if let Some(mcp) = &profile.mcp {
                let endpoint = self.policy.rules.iter().any(|r| {
                    r.permission == Permission::Proxy
                        && r.effect != klav_core::policy::Effect::Deny
                        && r.scope.items.contains(&profile.item_id)
                        && r.scope.domains.iter().any(|d| d.matches(&host))
                        && r.scope
                            .path_prefixes
                            .iter()
                            .any(|p| p.matches(&mcp.endpoint))
                });
                if !endpoint {
                    return Err(format!(
                        "profile {}: no proxy rule lets its item reach its MCP endpoint {} on {host}",
                        profile.name, mcp.endpoint
                    ));
                }
            }
        }
        self.check_mcp()
    }

    /// Whether the payload uses anything of `v: 4` (ADR 0049 §2.1).
    pub fn uses_mcp(&self) -> bool {
        self.profiles.iter().any(|p| p.mcp.is_some())
            || self.policy.needs_v4()
            || !self.local_clients.is_empty()
    }

    /// The `v: 4` rules: tool rules only on MCP profiles' items, and local
    /// clients only on a proxy's grant, each with a valid name, a 32-byte
    /// digest, and one or more of its MCP profiles; names and digests
    /// unique.
    fn check_mcp(&self) -> Result<(), String> {
        let mcp_items: std::collections::HashSet<ItemId> = self
            .profiles
            .iter()
            .filter(|p| p.mcp.is_some())
            .map(|p| p.item_id)
            .collect();
        for rule in self.policy.rules.iter().filter(|r| r.scope.uses_mcp()) {
            if rule.scope.items.is_empty()
                || !rule.scope.items.iter().all(|i| mcp_items.contains(i))
            {
                return Err(
                    "a rule with MCP tools names only items of MCP profiles, and at least one"
                        .into(),
                );
            }
        }
        if self.local_clients.is_empty() {
            return Ok(());
        }
        if self.profiles.is_empty() {
            return Err("only a grant with profiles (a credential proxy) has local clients".into());
        }
        if self.local_clients.len() > MAX_LOCAL_CLIENTS {
            return Err(format!("at most {MAX_LOCAL_CLIENTS} local clients"));
        }
        let mcp_profiles: std::collections::HashSet<&str> = self
            .profiles
            .iter()
            .filter(|p| p.mcp.is_some())
            .map(|p| p.name.as_str())
            .collect();
        let mut names = std::collections::HashSet::new();
        let mut digests = std::collections::HashSet::new();
        for client in &self.local_clients {
            if !klav_core::policy::local_client_name_ok(&client.name)
                || !names.insert(client.name.as_str())
            {
                return Err(format!(
                    "local client {:?}: 1–32 of a-z, 0-9 and -, and not twice",
                    client.name
                ));
            }
            if client.token_digest.as_bytes().len() != 32
                || !digests.insert(client.token_digest.as_bytes())
            {
                return Err(format!(
                    "local client {}: the token digest is 32 bytes and not another client's",
                    client.name
                ));
            }
            if client.profiles.is_empty() {
                return Err(format!("local client {}: no profiles", client.name));
            }
            let mut seen = std::collections::HashSet::new();
            for name in &client.profiles {
                if !mcp_profiles.contains(name.as_str()) || !seen.insert(name.as_str()) {
                    return Err(format!(
                        "local client {}: profile {name} is not an MCP profile of this grant or appears twice",
                        client.name
                    ));
                }
            }
        }
        Ok(())
    }

    /// The local client `name` of this grant that may use `profile`, if
    /// any: what the server checks `AccessRequest::local_client` against.
    pub fn local_client_for(&self, name: &str, profile: &str) -> Option<&LocalClient> {
        self.local_clients
            .iter()
            .find(|c| c.name == name && c.profiles.iter().any(|p| p == profile))
    }

    /// The `v: 3` rules: issuers only on a grant with profiles, each a
    /// different agent (not this one) with a valid identity, at least one of
    /// this grant's profiles and its limits in range; `sandbox` only on a
    /// grant that is not a proxy's, naming another agent with a valid
    /// identity and address.
    fn check_sandboxes(&self) -> Result<(), String> {
        if !self.issuers.is_empty() && self.profiles.is_empty() {
            return Err("only a grant with profiles (a credential proxy) has issuers".into());
        }
        if self.sandbox.is_some()
            && (!self.items.is_empty() || !self.profiles.is_empty() || !self.issuers.is_empty())
        {
            return Err("a credential proxy is never an issuer of sandboxes".into());
        }
        let profiles: std::collections::HashSet<&str> =
            self.profiles.iter().map(|p| p.name.as_str()).collect();
        let mut agents = std::collections::HashSet::new();
        for issuer in &self.issuers {
            if issuer.agent_id == self.agent_id || !agents.insert(issuer.agent_id) {
                return Err(format!(
                    "issuer {} appears twice or is the proxy itself",
                    issuer.agent_id
                ));
            }
            klav_core::crypto::identity::PublicIdentity::decode(issuer.public_identity.as_bytes())
                .map_err(|_| format!("issuer {}: invalid public identity", issuer.agent_id))?;
            if issuer.profiles.is_empty() {
                return Err(format!("issuer {}: no profiles", issuer.agent_id));
            }
            if issuer.profiles.len() > MAX_ISSUER_PROFILES {
                return Err(format!(
                    "issuer {}: at most {MAX_ISSUER_PROFILES} profiles",
                    issuer.agent_id
                ));
            }
            let mut seen = std::collections::HashSet::new();
            for name in &issuer.profiles {
                if !profiles.contains(name.as_str()) || !seen.insert(name.as_str()) {
                    return Err(format!(
                        "issuer {}: profile {name} is not in this grant or appears twice",
                        issuer.agent_id
                    ));
                }
            }
            if !(MIN_SANDBOX_TTL_SECS..=MAX_SANDBOX_TTL_SECS).contains(&issuer.max_ttl_secs) {
                return Err(format!(
                    "issuer {}: the TTL limit must be {MIN_SANDBOX_TTL_SECS}–{MAX_SANDBOX_TTL_SECS} s",
                    issuer.agent_id
                ));
            }
            if !(1..=MAX_LIVE_SANDBOXES).contains(&issuer.max_live) {
                return Err(format!(
                    "issuer {}: live sandboxes must be 1–{MAX_LIVE_SANDBOXES}",
                    issuer.agent_id
                ));
            }
        }
        if let Some(IssuerGrant { proxy: Some(proxy) }) = &self.sandbox {
            if proxy.agent_id == self.agent_id {
                return Err("an issuer cannot be its own proxy".into());
            }
            klav_core::crypto::identity::PublicIdentity::decode(proxy.public_identity.as_bytes())
                .map_err(|_| "the sandbox proxy has an invalid public identity".to_owned())?;
            klav_core::crypto::sandbox::check_proxy_url(&proxy.url)
                .map_err(|e| format!("the sandbox proxy address: {e}"))?;
        }
        Ok(())
    }

    /// The `v` to write when re-signing a grant that had `previous`: what
    /// it carries now, never lowering 2 to 1 (older clients already read
    /// it as 2), 3 only while it carries `issuers` or `sandbox`, and 4 only
    /// while it carries something of the MCP gateway.
    pub fn version_after(&self, previous: u32) -> u32 {
        self.needed_version()
            .max(previous.min(GRANT_PAYLOAD_VERSION_ITEMS))
    }

    /// The `v` this payload needs: 4 with anything of the MCP gateway, 3
    /// with sandbox issuers or a sandbox proxy, 2 with items, profiles or
    /// proxy rules, else 1.
    pub fn needed_version(&self) -> u32 {
        if self.uses_mcp() {
            GRANT_PAYLOAD_VERSION_MCP
        } else if !self.issuers.is_empty() || self.sandbox.is_some() {
            GRANT_PAYLOAD_VERSION_SANDBOXES
        } else if !self.items.is_empty() || !self.profiles.is_empty() || self.policy.needs_v2() {
            GRANT_PAYLOAD_VERSION_ITEMS
        } else {
            GRANT_PAYLOAD_VERSION
        }
    }
}

