//! Agents (design §5, `docs/api.md` §8): registration, grants and the
//! identity of signed agent requests.
//!
//! An agent has its own identity (X25519 + Ed25519, spec §6). It registers
//! with a request the person approves after comparing the 6-word pairing
//! code; the person's client then uploads a **grant** signed with the
//! account identity: the policy plus the keys of the shared projects,
//! wrapped with HPKE for the agent (kind `0x21`). The server stores the
//! grant verbatim and never sees a key in clear.
//!
//! Agent requests carry no bearer token: each one is signed with the
//! agent's Ed25519 key over method, path, time, nonce and body digest
//! (spec §13.3), in the `Klav-*` headers below.

use klav_core::ids::{AccountId, AgentId, ApprovalId, ItemId, ProjectId, TaskId, VaultId};
use klav_core::policy::{Permission, Policy};
use serde::{Deserialize, Serialize};

use crate::Blob;

